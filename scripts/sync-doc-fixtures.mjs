import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/fixtures/docs");
mkdirSync(outDir, { recursive: true });

// roblox-ts copies source text into long strings and does not unescape. A JSON
// string of the whole doc becomes [[\n\n# ...]] and the preview shows literal \n.
function tsString(text) {
	if (!text.includes('"') || !text.includes("'")) return JSON.stringify(text);
	const parts = text.split('"');
	const exprs = [];
	for (let i = 0; i < parts.length; i++) {
		if (parts[i].length > 0) exprs.push(JSON.stringify(parts[i]));
		if (i < parts.length - 1) exprs.push(JSON.stringify('"'));
	}
	return exprs.join(" .. ");
}

function emit(name, sourcePath, fallback) {
	let body;
	try {
		body = readFileSync(sourcePath, "utf8");
	} catch {
		body = fallback;
	}
	// strip HTML img tags — markdown subset has no images
	body = body.replace(/<img\b[^>]*>/gi, "");
	const lines = body.split(/\r?\n/).map((line) => `\t${tsString(line)},`);
	const file = join(outDir, `${name}.ts`);
	const source = `// Generated by scripts/sync-doc-fixtures.mjs — do not edit by hand.\nexport const ${name} = [\n${lines.join("\n")}\n].join("\\n");\n`;
	if (!source.includes('.join("\\n")')) throw new Error(`${name} separator missing`);
	writeFileSync(file, source);
	console.log(`wrote ${file} (${body.length} chars, ${lines.length} lines)`);
}

// Prefer UIBLOX_STYLING, else a sibling checkout next to this repo.
const stylingPath =
	process.env.UIBLOX_STYLING ||
	join(root, "../uiblox-rbxts/docs/STYLING.md");
const stylingFallback = existsSync(stylingPath)
	? readFileSync(stylingPath, "utf8")
	: "# Uiblox styling\n\nSee the uiblox-rbxts repo `docs/STYLING.md`.\n";
emit("stylingGuide", stylingPath, stylingFallback);
emit("pluginReadme", join(root, "README.md"), "# storyblox\n");
