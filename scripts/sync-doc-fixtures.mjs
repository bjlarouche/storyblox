import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/fixtures/docs");
mkdirSync(outDir, { recursive: true });

function emit(name, sourcePath, fallback) {
	let body;
	try {
		body = readFileSync(sourcePath, "utf8");
	} catch {
		body = fallback;
	}
	// strip HTML img tags — markdown subset has no images
	body = body.replace(/<img\b[^>]*>/gi, "");
	const file = join(outDir, `${name}.ts`);
	writeFileSync(file, `// Generated by scripts/sync-doc-fixtures.mjs — do not edit by hand.\nexport const ${name} = ${JSON.stringify(body)};\n`);
	console.log(`wrote ${file} (${body.length} chars)`);
}

const uibloxStyling = join(root, "../uiblox-markdown-editor/docs/STYLING.md");
const altStyling = "/Users/blarouche/Documents/GitHub/uiblox-rbxts/docs/STYLING.md";
emit(
	"stylingGuide",
	uibloxStyling,
	readFileSync(altStyling, "utf8"),
);
emit("pluginReadme", join(root, "README.md"), "# storyblox\n");
